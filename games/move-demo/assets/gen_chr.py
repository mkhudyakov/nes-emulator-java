#!/usr/bin/env python3
"""Generate chr.bin (8 KB) for the move-demo: background tiles + a 16x16 mascot.

Pixel values 0..3 are colour indices into whichever NES palette the tile uses.
Tile bytes are the standard 2-plane NES format (8 low-bit bytes, 8 high-bit).
"""
import os

def tile(rows):
    assert len(rows) == 8 and all(len(r) == 8 for r in rows)
    lo, hi = [], []
    for r in rows:
        a = b = 0
        for px in r:
            v = int(px)
            a = (a << 1) | (v & 1)
            b = (b << 1) | ((v >> 1) & 1)
        lo.append(a); hi.append(b)
    return bytes(lo + hi)

BLANK = ["00000000"] * 8
bg = [bytes(16)] * 256
sp = [bytes(16)] * 256

# ---- background tiles ----
bg[0x00] = tile(BLANK)                       # sky (shows backdrop colour)
bg[0x01] = tile([                            # grass top
    "11111111","12121212","11111111","22222222",
    "22222222","22322232","22222222","23222223"])
bg[0x02] = tile([                            # dirt
    "22222222","22322222","22222222","22222322",
    "23222222","22222222","22222232","22222222"])
bg[0x03] = tile([                            # brick block
    "11111111","13333331","13333331","13333331",
    "13333331","13333331","13333331","11111111"])
bg[0x04] = tile([                            # platform ledge
    "11111111","13222231","12222221","12222221",
    "12222221","12222221","13333331","11111111"])
bg[0x05] = tile([                            # cloud puff
    "00011100","00111110","01111111","11111111",
    "11111111","01111110","00000000","00000000"])

# ---- mascot sprite: a friendly 16x16 character ----
# colour 1 = body, 2 = white (eyes/belly), 3 = dark outline/pupil, 0 = clear.
def put16(base, grid16):
    assert len(grid16) == 16 and all(len(r) == 16 for r in grid16)
    sp[base+0] = tile([r[0:8]  for r in grid16[0:8]])
    sp[base+1] = tile([r[8:16] for r in grid16[0:8]])
    sp[base+2] = tile([r[0:8]  for r in grid16[8:16]])
    sp[base+3] = tile([r[8:16] for r in grid16[8:16]])

